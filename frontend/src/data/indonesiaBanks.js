const BY_VALUE = Object.fromEntries(INDONESIA_BANKS.map((b) => [b.value, b]));

// Resolve a stored value OR a legacy free-text name to a canonical entry (best effort).
export function findBank(input) {
  if (!input) return null;
  if (BY_VALUE[input]) return BY_VALUE[input];
  const norm = String(input).toLowerCase().replace(/[^a-z0-9]/g, "");
  return (
    INDONESIA_BANKS.find((b) => b.value.replace(/[^a-z0-9]/g, "") === norm) ||
    INDONESIA_BANKS.find((b) => b.label.toLowerCase().replace(/[^a-z0-9]/g, "") === norm) ||
    null
  );
}

export const bankLabel = (input) => (findBank(input)?.label || input || "—");
